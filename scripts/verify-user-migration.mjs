import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readdir,copyFile} from 'node:fs/promises';
import path from 'node:path';
import net from 'node:net';
import pg from 'pg';
import {root} from './lib/config.mjs';
import {startLocalDatabase} from './lib/database.mjs';
import {migrate} from './lib/migrations.mjs';
process.env.NODE_ENV='development';
const directory=await mkdtemp(path.join(root,'artifacts/user-migration-'));
const old=path.join(directory,'migrations');await mkdir(old);
for(const name of await readdir(path.join(root,'db/migrations')))if(name.endsWith('.sql')&&name<'016')await copyFile(path.join(root,'db/migrations',name),path.join(old,name));
const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
let db,c;
try{
 db=await startLocalDatabase({directory,port});await migrate(db.connectionString,old);
 c=new pg.Client({connectionString:db.connectionString});await c.connect();
 const user=(await c.query("INSERT INTO users(phone,password_hash,role) VALUES('+8613800000999','test-hash','platform_admin') RETURNING *")).rows[0];
 const ordinary=(await c.query("INSERT INTO users(phone,password_hash,account) VALUES('+8613800000888','retained-hash','legacy_owner') RETURNING *")).rows[0];
 await c.query("INSERT INTO sessions(user_id,token_hash,login_version,expires_at) VALUES($1,'ordinary-session',0,clock_timestamp()+interval '1 day')",[ordinary.id]);
 await c.query("INSERT INTO sessions(user_id,token_hash,login_version,expires_at) VALUES($1,'migration-test',0,clock_timestamp()+interval '1 day')",[user.id]);
 const activity=(await c.query("INSERT INTO activities(owner_id,name,expires_at) VALUES($1,'历史活动',clock_timestamp()+interval '1 day') RETURNING *",[user.id])).rows[0];
 const credential=(await c.query("INSERT INTO wechat_credentials(id,app_id,account_name,sealed_secret) VALUES(gen_random_uuid(),'legacy-test','历史号','{}') RETURNING id")).rows[0].id;
 await c.query("UPDATE wechat_configurations SET credential_id=$1 WHERE scope='platform'",[credential]);
 await c.query("INSERT INTO wechat_configurations(scope,source,credential_id) VALUES($1,'platform',$2)",[activity.id,credential]);
 assert.deepEqual(await migrate(db.connectionString),['016_user_only.sql','017_local_accounts.sql','018_ten_person_rounds.sql','019_wechat_readiness.sql','020_roster_revisions.sql','021_activity_materials.sql']);
 const current=(await c.query('SELECT * FROM users WHERE id=$1',[user.id])).rows[0];
 assert.equal(current.role,'user');assert.equal(current.phone,user.phone);assert.equal(current.password_hash,user.password_hash);
 assert.equal(current.login_name,'13800000999');
 const retained=(await c.query('SELECT * FROM users WHERE id=$1',[ordinary.id])).rows[0];
 assert.equal(retained.login_name,'13800000888');assert.equal(retained.account,'legacy_owner');
 assert.equal(retained.password_hash,ordinary.password_hash);assert.equal(retained.login_version,ordinary.login_version);
 assert.equal((await c.query("SELECT * FROM sessions WHERE user_id=$1 AND token_hash='ordinary-session'",[ordinary.id])).rowCount,1);
 assert.equal((await c.query('SELECT * FROM sessions WHERE user_id=$1',[user.id])).rowCount,0);
 assert.equal((await c.query('SELECT * FROM activities WHERE id=$1',[activity.id])).rowCount,1);
 assert.equal((await c.query('SELECT credential_id FROM wechat_configurations WHERE scope=$1',[activity.id])).rows[0].credential_id,credential);
 assert.equal((await c.query("SELECT * FROM wechat_configurations WHERE scope='platform'")).rowCount,0);
 await assert.rejects(c.query("UPDATE users SET role='platform_admin' WHERE id=$1",[user.id]),e=>e.code==='23514');
 assert.deepEqual(await migrate(db.connectionString),[]);
 console.info('PASS migration: normal account, revoked session, preserved activity and binding, no platform default, role constraint, repeat safe');
}finally{await c?.end();await db?.stop();}
